"""三元组数据模型 —— 知识图谱的最小知识单元

Python 3.12 | 依赖：networkx | 运行：python 01_triple.py
演示：手工构建一个小图谱，并做基础查询
术语：三元组(Triple)=(头实体,关系,尾实体)；DiGraph=有向图(边有方向)
"""

import networkx as nx

# ============================================================
# ① 构建图谱：把"事实"存成三元组
# ============================================================

# 知识点 1.1：三元组是什么
# 一句"事实" = 一个三元组：(头实体, 关系, 尾实体)
#   "马云是阿里巴巴的创始人" → (马云, 创始人, 阿里巴巴)
# 实体 = 人/公司/城市等对象，是图谱的"节点"
# 关系 = 实体间的语义联系，是图谱的"边"
# 为什么要这样拆？因为任何知识都能用这种主-谓-宾结构表达，机器才方便存和查

# 知识点 1.2：用有向图(DiGraph)存储三元组
# networkx 的 DiGraph = 有向图：每个边都带方向，正好表达关系的方向性
# （"创始人"从马云指向阿里巴巴，"总部位于"从公司指向城市）

def demo01_build():
    """① 构建图谱（每个事实一个三元组）"""
    print("① 构建图谱（每个事实一个三元组）")

    g = nx.DiGraph()  # DiGraph：有向图，add_edge 时自动创建节点

    # 三元组列表：(头实体, 尾实体, 关系名)
    facts = [
        ("马云", "阿里巴巴", "创始人"),
        ("张勇", "阿里巴巴", "CEO"),
        ("马云", "蚂蚁集团", "创始人"),
        ("阿里巴巴", "杭州", "总部位于"),
        ("蚂蚁集团", "杭州", "总部位于"),
        ("杭州", "浙江", "省会"),
        ("浙江", "中国", "属于"),
    ]
    for head, tail, rel in facts:
        # add_edge 存边；relation= 把关系名作为边的属性挂上去（不挂就丢了关系语义）
        g.add_edge(head, tail, relation=rel)

    print(f"  实体数: {g.number_of_nodes()}")
    print(f"  三元组数: {g.number_of_edges()}")
    print(f"  实体列表: {list(g.nodes)}")

    print("\n  全部关系:")
    for head, tail in g.edges:
        # g[head][tail] 是这条边的属性字典，['relation'] 取出关系名
        print(f"    ({head}) --[{g[head][tail]['relation']}]--> ({tail})")

    return g


# ============================================================
# ② 查询图谱：顺着关系找答案
# ============================================================

def demo02_query(g: nx.DiGraph):
    """② 顺着关系查答案"""

    # 知识点 2.1：正向查询 successors —— "从某实体出发能到哪"
    # successors(节点) = 该节点所有边的出节点（有向图的"下游"）
    # 问"马云创建了哪些公司" = 从马云出发能到达的实体

    reach = list(g.successors("马云"))
    print(f"② 马云 → {reach}")

    # 知识点 2.2：按关系过滤 —— "A 和 B 之间是什么关系" 的高级版：
    # 不只看"能到哪"，还要求关系名匹配。这就是三元组查询的本质：
    # (头实体固定, 关系固定, 尾实体任意) → 找出所有满足的事实
    # 问"谁创立了阿里巴巴" = 所有指向阿里巴巴且关系=创始人的实体

    founders = [h for h, t in g.edges
                if t == "阿里巴巴" and g[h][t]["relation"] == "创始人"]
    print(f"  阿里巴巴的创始人: {founders}")

    # 知识点 2.3：多跳路径 —— 顺着边一步一步走
    # 单步只能答"总部在哪"，多跳才能答"总部在哪个省"
    # 路径查询是知识图谱相对关系数据库的核心优势：多表 join 要写很长 SQL

    for h, t in g.edges:
        if h == "阿里巴巴" and g[h][t]["relation"] == "总部位于":
            city = t
            for h2, t2 in g.edges:          # 第二跳：city → 省会 → ?
                if h2 == city and g[h2][t2]["relation"] == "省会":
                    print(f"  阿里巴巴总部: {city}，是 {t2} 的省会")

    # 知识点 2.4：反向查询 predecessors —— "谁指向了某实体"
    # predecessors(节点) = 所有边的入节点（有向图的"上游"）
    # 问"哪些实体和阿里巴巴有关系"（不看方向只看连接）

    sub = list(g.predecessors("阿里巴巴"))
    print(f"  指向阿里巴巴的实体: {sub}")


# ============================================================
# ③ 属性：实体的固有信息
# ============================================================

def demo03_attribute(g: nx.DiGraph):
    """③ 给实体补充属性"""

    # 知识点 3.1：节点属性 vs 三元组
    # 属性 = 实体的固有信息（成立时间/人口/市值），存成键值对
    # 为什么不也用三元组存？关系是"实体-实体"的连接，属性是"实体-值"的描述；
    # 属性放节点上，查询和展示都更快；RDF 模型则倾向全部三元组化（见 02_rdf.py）

    g.nodes["阿里巴巴"]["成立时间"] = "1999年"
    g.nodes["杭州"]["人口"] = 1250  # 万

    for node in ["阿里巴巴", "杭州"]:
        print(f"  {node}: {dict(g.nodes[node])}")


if __name__ == "__main__":
    graph = demo01_build()
    demo02_query(graph)
    demo03_attribute(graph)
